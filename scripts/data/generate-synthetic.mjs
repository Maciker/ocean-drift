#!/usr/bin/env node
/**
 * Builds a clearly labeled synthetic surface-current episode for local engine work.
 * Not Copernicus data — do not present as real in demos.
 */
import { createHash } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const outDir = join(root, 'src/data/episodes/synthetic-steady')

const west = 1.5
const east = 6.5
const south = 38.5
const north = 43.5
const lonStep = 0.5
const latStep = 0.5
const stepHours = 1
const hours = 72
const start = new Date('2024-09-01T00:00:00.000Z')

const lon = []
for (let x = west; x <= east + 1e-9; x += lonStep) lon.push(Number(x.toFixed(2)))
const lat = []
for (let y = south; y <= north + 1e-9; y += latStep) lat.push(Number(y.toFixed(2)))

const timesUtc = []
for (let h = 0; h <= hours; h += stepHours) {
  timesUtc.push(new Date(start.getTime() + h * 3600_000).toISOString())
}

/** Steady eastward 0.25 m/s with a weak northward shear — analytic and deterministic. */
const U0 = 0.25
const V_SHEAR = 0.05

const u = []
const v = []
for (let t = 0; t < timesUtc.length; t += 1) {
  const uPlane = []
  const vPlane = []
  for (let j = 0; j < lat.length; j += 1) {
    const uRow = []
    const vRow = []
    const latValue = lat[j]
    for (let i = 0; i < lon.length; i += 1) {
      // Soft land mask near northern edge of the box (toy coastline).
      const onLand = latValue > 43.1
      if (onLand) {
        uRow.push(null)
        vRow.push(null)
      } else {
        uRow.push(U0)
        vRow.push(Number((((latValue - south) / (north - south)) * V_SHEAR).toFixed(4)))
      }
    }
    uPlane.push(uRow)
    vPlane.push(vRow)
  }
  u.push(uPlane)
  v.push(vPlane)
}

const field = {
  timesUtc,
  lon,
  lat,
  u,
  v,
}

const currentsJson = `${JSON.stringify(field)}\n`
const sha256 = createHash('sha256').update(currentsJson, 'utf8').digest('hex')

const manifest = {
  id: 'synthetic-steady',
  kind: 'synthetic',
  productId: 'SYNTHETIC_NOT_COPERNICUS',
  datasetId: 'synthetic-steady-eastward',
  regionLabel: 'Western Mediterranean toy box',
  bbox: { west, east, south, north },
  startUtc: timesUtc[0],
  endUtc: timesUtc[timesUtc.length - 1],
  stepHours,
  depthLabel: 'surface (synthetic)',
  units: 'm/s',
  uvConvention: 'oceanographic-east-north',
  landMask: 'null-velocity',
  citation: 'Synthetic fixture for OceanDrift tests — not E.U. Copernicus Marine Service Information.',
  sourceCommitNote: 'Generated by scripts/data/generate-synthetic.mjs',
  currentsFile: 'currents.json',
  currentsSha256: sha256,
  sizeBytes: Buffer.byteLength(currentsJson, 'utf8'),
}

mkdirSync(outDir, { recursive: true })
writeFileSync(join(outDir, 'currents.json'), currentsJson)
writeFileSync(join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`)
writeFileSync(
  join(outDir, 'README.md'),
  `# synthetic-steady

**Kind:** synthetic (not Copernicus).

Steady eastward surface current (~0.25 m/s) with weak northward shear and a toy land mask near the northern edge. Used for drift-engine tests and UI wiring until a real episode is fetched (see \`docs/data-pipeline.md\`).

Do not show this fixture in the hackathon pitch as real Copernicus data.
`,
)

console.log(
  JSON.stringify(
    {
      outDir,
      times: timesUtc.length,
      lon: lon.length,
      lat: lat.length,
      sizeBytes: manifest.sizeBytes,
      sha256,
    },
    null,
    2,
  ),
)
